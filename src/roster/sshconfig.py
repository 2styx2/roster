"""ssh config files: the one writer and reader of the `Host NAME` blocks roster writes (this Box's ssh config for an
Inventory, the Box key rotation's one-Host config, the Mesh's config on a source Host), the header that says roster
wrote a file and from which roster.yml, the values that may go in one, and ~/.ssh/config's Include lines."""

import os
import re
import shlex
from pathlib import Path
from typing import NamedTuple

from .common import ssh_path
from .context import ssh_dir

# What may never go into a value roster writes into an ssh config file: a quote would end the value and a control
# character (a newline above all) the line, so the rest would be read as directives of its own.
SSH_UNSAFE = re.compile(r'["\x00-\x1f\x7f]')
HEADER = "# Generated by roster from "


def ssh_quote(path: str | Path, tokens: bool = False) -> str:
    """PATH as one quoted value of an ssh config line. A quote or a control character in it is refused (ValueError): it
    could end the value or the line, and what followed would be read as directives. TOKENS: the option expands
    %-tokens (IdentityFile, UserKnownHostsFile, ControlPath), so a % of the path itself is written %%."""
    s = ssh_path(path)
    if SSH_UNSAFE.search(s):
        raise ValueError(f"{s!r} can't go into an ssh config: it holds a quote or a control character")
    return f'"{s.replace("%", "%%") if tokens else s}"'


def token_path(path: str | Path) -> str:
    """PATH for an option that expands %-tokens."""
    return ssh_quote(path, tokens=True)


def comment(text) -> str:
    """TEXT on a comment line: no control character can end the line early."""
    return re.sub(r"[\x00-\x1f\x7f]", "?", str(text))


def header(source) -> str:
    """The first line of an ssh config roster writes from the roster.yml SOURCE."""
    return HEADER + comment(source)


def source_of(path: Path) -> Path | None:
    """The roster.yml the ssh config at PATH was written from, by its header (None: not roster's, or not there)."""
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            first = f.readline().rstrip("\n")
    except OSError:
        return None
    return Path(first[len(HEADER):]) if first.startswith(HEADER) else None


def generated(path: Path) -> bool:
    """Did roster write the ssh config file at PATH? A file by an old name of roster's could be the user's own: only
    roster's are moved or deleted."""
    return source_of(path) is not None


def host_block(name: str, options: list[tuple[str, object]]) -> list[str]:
    """`Host NAME` and its OPTIONS ((keyword, value), in order), as lines. HostName's value has its % written %% (ssh
    expands %-tokens in it)."""
    return [f"Host {name}"] + [f"    {k} {str(v).replace('%', '%%') if k == 'HostName' else v}" for k, v in options]


class Block(NamedTuple):
    """One Host block of a file roster wrote: its Host, its text with the comment lines above it, and its lines
    from `Host` on."""

    host: str
    text: str
    lines: list[str]


def blocks(path: Path) -> list[Block]:
    """The Host blocks of an ssh config file roster wrote (blocks are separated by a blank line), in order; [] when
    there's no such file."""
    try:
        text = path.read_text()
    except OSError:
        return []
    out: list[Block] = []
    for chunk in text.split("\n\n"):
        lines = chunk.strip("\n").splitlines()
        at = [i for i, ln in enumerate(lines) if ln.startswith("Host ")]
        if len(at) == 1:
            out.append(Block(lines[at[0]][5:].strip(), chunk.strip("\n"), lines[at[0]:]))
    return out


def written_block(path: Path, name: str) -> list[str] | None:
    """The `Host NAME` block in the file at PATH as it is now, as lines; None if it isn't there."""
    return next((b.lines for b in blocks(path) if b.host == name), None)


# ---------------------------------------------------------------- ~/.ssh/config's Include lines

def main_config() -> Path:
    return ssh_dir() / "config"


def include_line(path: Path) -> str:
    return f"Include {ssh_quote(path)}"


def include_targets(line: str) -> list[str]:
    """The files an `Include` line of ~/.ssh/config names (ssh_path form, ~ and relative paths resolved as ssh does);
    [] for any other line."""
    words = line.strip().replace("=", " ", 1).split(None, 1)
    if len(words) != 2 or words[0].lower() != "include":
        return []
    try:
        args = shlex.split(words[1])
    except ValueError:
        return []
    out: list[str] = []
    for a in args:
        p = Path(os.path.expanduser(a))
        out.append(ssh_path(p if p.is_absolute() else ssh_dir() / p))
    return out


def includes(text: str, path: Path) -> bool:
    """Does the ssh config TEXT include PATH itself (a whole Include line, however written; not a longer name)?"""
    want = ssh_path(path)
    return any(want in include_targets(line) for line in text.splitlines())
