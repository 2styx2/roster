"""Named Inventories (ticket 115, #201): one person may have several, the team's for work and their own for home, and
one is active. The list is a small data file in roster's own folder (inventories.json), never in init.lua or a
roster.yml. It names each Inventory's file; the files themselves stay where they are.

Each named Inventory gets its own generated ssh config (~/.ssh/config.d/roster-NAME) and known_hosts
(~/.ssh/roster_known_hosts-NAME); ROSTER.md is written next to its roster.yml, as always. ~/.ssh/config includes
one index (config.d/roster.inventories) that includes the active Inventory's ssh config first and the others after,
so `ssh pi` works for any of them and on a name clash the active one wins. With no named Inventories none of this
exists and roster writes and reads exactly what it always did."""

from __future__ import annotations

import json
import os
import shutil
from pathlib import Path
from typing import Any, NamedTuple, NoReturn, cast

from pydantic import BaseModel, ConfigDict, ValidationError

from .common import (
    NAME_RE,
    die,
    known_hosts_file,
    ssh_config_file,
    ssh_dir,
    ssh_index_file,
    ssh_path,
    user_config_dir,
)

INDEX_HEAD = ("# Generated by roster: each named Inventory's ssh config, the active one first (it wins a name clash).\n"
              "# Don't edit by hand: `roster inv use` and `roster sync` rewrite it.\n")


class Named(BaseModel, frozen=True):
    """One named Inventory: its NAME and the absolute PATH of its roster.yml."""

    model_config = ConfigDict(extra="forbid")
    name: str
    path: Path

    def view(self, active: str | None) -> dict[str, Any]:
        return {"name": self.name, "path": str(self.path), "active": self.name == active, "exists": self.path.is_file()}


class Inventories(BaseModel, frozen=True):
    """inventories.json: the named Inventories in the order they were added (`inventories`), and the active one's name
    (or None)."""

    model_config = ConfigDict(extra="forbid")
    active: str | None = None
    inventories: tuple[Named, ...] = ()

    def get(self, name: str | None) -> Named | None:
        return next((x for x in self.inventories if x.name == name), None)

    def view(self) -> dict[str, Any]:
        return {"active": self.active, "inventories": [x.view(self.active) for x in self.inventories]}


def list_file():
    return user_config_dir() / "inventories.json"


def load() -> Inventories:
    """The named Inventories (none when the file isn't there). A file that doesn't read is an error, with its fix."""
    f = list_file()
    if not f.exists():
        return Inventories()
    try:
        inv = Inventories.model_validate(json.loads(f.read_text()))
    except (OSError, ValueError, ValidationError) as e:
        die(f"{f} doesn't load ({type(e).__name__}) - fix it, or delete it to forget every named Inventory")
    if inv.active is not None and inv.get(inv.active) is None:
        inv = inv.model_copy(update={"active": None})
    return inv


def save(inv: Inventories) -> None:
    f = list_file()
    f.parent.mkdir(parents=True, exist_ok=True)
    tmp = f.with_suffix(".new")
    tmp.write_text(inv.model_dump_json(indent=2) + "\n")
    os.replace(tmp, f)


def same_file(a: str | Path, b: str | Path) -> bool:
    return Path(a).expanduser().resolve() == Path(b).expanduser().resolve()


def unknown(name: str, inv: Inventories | None = None) -> NoReturn:
    inv = inv or load()
    have = ", ".join(x.name for x in inv.inventories) or "none yet"
    die(f"no Inventory named '{name}' (named: {have}) - `roster inv list` lists them, `roster inv add NAME PATH` "
        "names one")


def path_of(name: str) -> Path:
    """The roster.yml of the named Inventory NAME (`roster --inv NAME`); an unknown name is an error."""
    inv = load()
    x = inv.get(name)
    if x is None:
        unknown(name, inv)
    return x.path


def active_path() -> Path | None:
    """The active named Inventory's roster.yml, or None."""
    inv = load()
    x = inv.get(inv.active) if inv.active else None
    return x.path if x else None


def name_of(path: str | Path) -> str | None:
    """The name PATH is known by among the named Inventories, or None."""
    if not list_file().exists():
        return None
    return next((x.name for x in load().inventories if same_file(x.path, path)), None)


def add(name: str, path: str | Path) -> bool:
    """Name the roster.yml at PATH. The first one named becomes the active one. When this Box's ssh config was written
    from that same file before it had a name, its recorded host keys are kept for it (nothing is trusted anew)."""
    if not NAME_RE.match(name or ""):
        die(f"bad Inventory name {name!r} (use letters, digits, . _ -, starting with a letter or digit)")
    path = Path(path).expanduser().resolve()
    if not path.is_file():
        die(f"no file at {path} - give the path of the Inventory's roster.yml")
    inv = load()
    for x in inv.inventories:
        if x.name == name:
            die(f"there's already an Inventory named '{name}' ({x.path}) - pick another name, or "
                f"`roster inv remove {name}` first")
        if same_file(x.path, path):
            die(f"{path} is already the Inventory '{x.name}'")
        if x.path.parent == path.parent:
            die(f"{path.parent} already holds the Inventory '{x.name}', and ROSTER.md is written next to each "
                "roster.yml: keep each Inventory in its own folder")
    first = inv.active is None
    inv = Inventories(active=name if first else inv.active, inventories=(*inv.inventories, Named(name=name, path=path)))
    save(inv)
    adopt_known_hosts(name, path)
    refresh_index(inv)
    return first


def adopt_known_hosts(name: str, path: Path) -> None:
    """The host keys recorded for PATH before it had a name, copied to its own known_hosts (once)."""
    old, new = ssh_config_file(None), known_hosts_file(name)
    if new.exists() or not known_hosts_file(None).exists() or not old.is_file():
        return
    first = (old.read_text().splitlines() or [""])[0]
    if first.startswith("# Generated by roster from ") and same_file(first.removeprefix("# Generated by roster from "),
                                                                      path):
        shutil.copy2(known_hosts_file(None), new)
        os.chmod(new, 0o600)


def use(name: str) -> None:
    inv = load()
    if inv.get(name) is None:
        unknown(name, inv)
    inv = inv.model_copy(update={"active": name})
    save(inv)
    refresh_index(inv)


def remove(name: str) -> bool:
    """Forget NAME (its roster.yml stays). Its generated ssh config goes; its known_hosts stays, so naming it again
    trusts nothing anew. Returns whether it was the active one."""
    inv = load()
    x = inv.get(name)
    if x is None:
        unknown(name, inv)
    was_active = inv.active == name
    inv = Inventories(active=None if was_active else inv.active,
                      inventories=tuple(y for y in inv.inventories if y.name != name))
    save(inv)
    ssh_config_file(name).unlink(missing_ok=True)
    refresh_index(inv)
    return was_active


# ---------------------------------------------------------------- ~/.ssh/config: one include for them all

def include_line(path: Path) -> str:
    return f'Include "{ssh_path(path)}"'


def index_order(inv: Inventories) -> list[Path]:
    """The ssh config files the index includes, in order: the active Inventory's, the other named ones', then the one
    roster writes for a roster.yml that has no name (when there is one)."""
    names = ([inv.active] if inv.active else []) + [x.name for x in inv.inventories if x.name != inv.active]
    files = [ssh_config_file(n) for n in names]
    if ssh_config_file(None).is_file():
        files.append(ssh_config_file(None))
    return files


def refresh_index(inv: Inventories | None = None) -> None:
    """Rewrite the index and point ~/.ssh/config at it, once roster has written any ssh config here. With no named
    Inventories left, ~/.ssh/config includes roster's one file again and the index goes."""
    inv = inv or load()
    main = ssh_dir() / "config"
    text = main.read_text() if main.exists() else ""
    index, default = ssh_index_file(), ssh_config_file(None)
    if not inv.inventories:
        if index.exists():
            main.write_text(text.replace(include_line(index), include_line(default)))
            index.unlink()
        return
    if not (index.exists() or default.exists() or any(ssh_config_file(x.name).exists() for x in inv.inventories)):
        return                                  # nothing synced here yet: the first sync writes it
    index.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    index.write_text(INDEX_HEAD + "".join(include_line(f) + "\n" for f in index_order(inv)))
    os.chmod(index, 0o600)
    if ssh_path(index) in text:
        return
    lines = text.splitlines(keepends=True)
    if any(ln.strip() == include_line(default) for ln in lines):     # the one roster wrote: the index takes its place
        text = "".join(include_line(index) + "\n" if ln.strip() == include_line(default) else ln for ln in lines)
    else:                                       # an Include must sit above any Host block, so prepend it
        text = f"{include_line(index)}\n\n{text}"
    main.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    main.write_text(text)
    os.chmod(main, 0o600)


def included_files() -> list[str]:
    """The roster ssh config files ~/.ssh/config reaches: through the index, or roster's one file directly."""
    main = ssh_dir() / "config"
    if not main.is_file():
        return []
    text = main.read_text()
    out: list[str] = []
    index = ssh_index_file()
    if ssh_path(index) in text and index.is_file():
        out += [line.removeprefix('Include "').removesuffix('"') for line in index.read_text().splitlines()
                if line.startswith("Include ")]
    if ssh_path(ssh_config_file(None)) in text:
        out.append(ssh_path(ssh_config_file(None)))
    return out


# ---------------------------------------------------------------- the same machine in two Inventories

# (code, catalog row, fix) for each warning; the codes are errors.py's 144-147
WARNINGS = {
    "doesnt_load": (144, 192, "fix that file (`roster --inv {other} check --box` says why), or `roster inv remove "
                              "{other}` if you no longer use it"),
    "same_machine": (145, 193, "nothing to do if it's one machine you reach from both; if it isn't, one was cloned "
                               "with the other's host key: give it its own (`ssh-keygen -A` on it, then record it "
                               "again)"),
    "same_name": (146, 194, "rename one of them in its roster.yml, or reach the other with "
                            "`roster --inv {other} run {name} -- ...`"),
    "same_address": (147, 195, "nothing to do if the two are on different networks; if it's one machine, its key "
                               "changed: `roster check {name}` compares it with the recorded one"),
}


def warning(kind: str, message: str, **names: str) -> dict[str, Any]:
    code, row, fix = WARNINGS[kind]
    return {"code": code, "row": row, "message": message, "fix": fix.format(**names)}


class Machine(NamedTuple):
    """A Host as the comparison sees it: its name, address, ssh port and recorded host-key fingerprints."""

    name: str
    ip: str
    port: int
    keys: frozenset[str]


def machines(name: str | None, cfg: dict[str, Any]) -> list[Machine]:
    """The Hosts of the Inventory CFG, with the fingerprints recorded for each in the Inventory NAME's known_hosts."""
    import paramiko

    from .sshops import fingerprint, hk_name
    f = known_hosts_file(name)
    try:
        recorded = paramiko.HostKeys(str(f)) if f.is_file() else None
    except (OSError, ValueError, paramiko.SSHException):
        recorded = None
    out: list[Machine] = []
    hosts = cast("dict[str, dict[str, Any]]", cfg["hosts"])
    for h in hosts.values():
        found = recorded.lookup(hk_name(h)) if recorded is not None else None
        keys = frozenset(fingerprint(k) for k in found.values()) if found else frozenset[str]()
        out.append(Machine(str(h["name"]), str(h["ip"]), int(h["ssh"]["port"]), keys))
    return out


def overlaps(cfg: dict[str, Any]) -> list[dict[str, Any]]:
    """The warnings for the Inventory CFG (this run's) against every other named Inventory: the same host key, the
    same Host name, the same address and port with different keys. Never an error; compares fingerprints only."""
    from .common import current_inventory
    from .config import load_config
    if not list_file().exists():
        return []
    inv = load()
    here = current_inventory()
    others = [x for x in inv.inventories if x.name != here and not same_file(x.path, cfg["path"])]
    if not others:
        return []
    label = here or "this Inventory"
    mine = machines(here, cfg)
    out: list[dict[str, Any]] = []
    for x in others:
        try:
            theirs = machines(x.name, load_config(x.path))
        except SystemExit as e:
            why = str(e.code).removeprefix("error: ")
            out.append(warning("doesnt_load", f"the Inventory {x.name} isn't compared with this one: {why}",
                               other=x.name))
            continue
        reported: set[tuple[str, str]] = set()
        for h in mine:
            for o in theirs:
                if h.keys & o.keys:
                    reported.add((h.name, o.name))
                    out.append(warning("same_machine", f"`{h.name}` in {label} and `{o.name}` in {x.name} have "
                                                       "the same host key: the same machine?"))
        names = {o.name for o in theirs}
        for h in mine:
            if h.name in names and (h.name, h.name) not in reported:
                wins = label if here == inv.active else x.name if x.name == inv.active else None
                where = f"`ssh {h.name}` reaches {wins}'s (the active Inventory)" if wins else \
                    f"`ssh {h.name}` reaches the one listed first in `roster inv list`"
                out.append(warning("same_name", f"`{h.name}` is a Host in both {label} and {x.name}: {where}",
                                   other=x.name, name=h.name))
        for h in mine:
            for o in theirs:
                if (h.ip, h.port) == (o.ip, o.port) and h.keys and o.keys and not h.keys & o.keys:
                    out.append(warning("same_address", f"`{h.name}` in {label} and `{o.name}` in {x.name} are both "
                                                       f"{h.ip}:{h.port}, with different host keys: two networks "
                                                       "with the same addresses?", name=h.name))
    return out
