INDEX_HEAD = ("# Generated by roster: every named Inventory's Hosts, the active one's first. A Host name an earlier\n"
              "# Inventory has is left out of a later one, so `ssh NAME` reads one block. Don't edit by hand:\n"
              "# `roster sync`, `roster inv use`, `add` and `remove` rewrite it.\n")
SECTION = "#roster-from "              # a Host's own comments are "# TEXT": never this


def name_problem(name: str) -> str | None:
    """Why NAME can't be an Inventory's name, or None. Names become file names (roster-inventories/NAME) and ssh config text: the
    Host name rule, matched whole, and no trailing dot (Windows drops it, so `work.` would be `work`'s files)."""
    if not NAME_RE.match(name) or name.endswith("."):
        return (f"bad Inventory name {name!r} (use letters, digits, . _ -, starting with a letter or digit and not "
                "ending with a dot)")
    return None


def same_name(a: str | None, b: str | None) -> bool:
    """Inventory names compare without letter case: `Work` and `work` are one file on Windows and macOS."""
    return a is not None and b is not None and a.casefold() == b.casefold()


class Named(BaseModel, frozen=True):
    """One named Inventory: its NAME and the absolute PATH of its roster.yml."""

    model_config = ConfigDict(extra="forbid")
    name: str
    path: Path

    @field_validator("name")
    @classmethod
    def _name(cls, v: str) -> str:
        why = name_problem(v)
        if why:
            raise ValueError(why)
        return v

    @field_validator("path")
    @classmethod
    def _path(cls, v: Path) -> Path:
        if not v.is_absolute() or SSH_UNSAFE.search(str(v)):
            raise ValueError("an Inventory's path is absolute, with no quote or control character")
        return v

    def view(self, active: str | None) -> dict[str, Any]:
        return {"name": self.name, "path": str(self.path), "active": self.name == active, "exists": self.path.is_file()}


class Inventories(BaseModel, frozen=True):
    """inventories.json: the named Inventories in the order they were added (`inventories`), and the active one's name
    (or None)."""

    model_config = ConfigDict(extra="forbid")
    active: str | None = None
    inventories: tuple[Named, ...] = ()

    @field_validator("inventories")
    @classmethod
    def _distinct(cls, v: tuple[Named, ...]) -> tuple[Named, ...]:
        if len({x.name.casefold() for x in v}) != len(v):
            raise ValueError("two Inventories have the same name (letter case aside)")
        return v

    def get(self, name: str | None) -> Named | None:
        return next((x for x in self.inventories if same_name(x.name, name)), None)

    def view(self) -> dict[str, Any]:
        return {"active": self.active, "inventories": [x.view(self.active) for x in self.inventories]}


def list_file() -> Path:
    return user_config_dir() / "inventories.json"


def load() -> Inventories:
    """The named Inventories (none when the file isn't there). A file that doesn't load, or names something roster
    couldn't use safely (a name or path edited by hand), is an error, with its fix."""
    f = list_file()
    if not f.exists():
        return Inventories()
    try:
        inv = Inventories.model_validate(json.loads(f.read_text()))
    except (OSError, ValueError, ValidationError) as e:
        die(f"{f} doesn't load ({type(e).__name__}) - fix it, or delete it to forget every named Inventory")
    found = inv.get(inv.active)
    return inv.model_copy(update={"active": found.name if found else None})


def save(inv: Inventories) -> None:
    replace_file(list_file(), inv.model_dump_json(indent=2) + "\n", 0o600)


def same_file(a: str | Path, b: str | Path) -> bool:
    return Path(a).expanduser().resolve() == Path(b).expanduser().resolve()


def unknown(name: str, inv: Inventories | None = None) -> NoReturn:
    from .config import token_shaped
    inv = inv or load()
    have = ", ".join(x.name for x in inv.inventories) or "none yet"
    shown = "that (not repeated)" if token_shaped(name) else f"'{name}'"     # a token typed after --inv (#484 N1)
    die(f"no Inventory named {shown} (named: {have}) - `roster inv list` lists them, `roster inv add NAME PATH` "
        "names one")


def path_of(name: str) -> Path:
    """The roster.yml of the named Inventory NAME (`roster --inv NAME`); an unknown name is an error."""
    inv = load()
    x = inv.get(name)
    if x is None:
        unknown(name, inv)
    return x.path


def canonical(name: str) -> str:
    """NAME as it was named (letter case as given to `inv add`); an unknown name is an error."""
    inv = load()
    x = inv.get(name)
    if x is None:
        unknown(name, inv)
    return x.name


def active_path() -> Path | None:
    """The active named Inventory's roster.yml, or None."""
    inv = load()
    x = inv.get(inv.active) if inv.active else None
    return x.path if x else None


def name_of(path: str | Path) -> str | None:
    """The name PATH is known by among the named Inventories, or None."""
    if not list_file().exists():
        return None
    return next((x.name for x in load().inventories if same_file(x.path, path)), None)


class Added(NamedTuple):
    """What `inv add` did besides naming: whether the Inventory became the active one, and where the Mesh state it took
    over went (None when it took none)."""

    first: bool
    mesh_state: Path | None
    mesh_kept: str | None = None    # why the Box's mesh.json stayed with the unnamed Inventory (when it's there)


def add(name: str, path: str | Path) -> Added:
    """Name the roster.yml at PATH. The first one named becomes the active one. Its known_hosts starts as the one every
    roster.yml on this Box shared before named Inventories, so no host key the Box trusted is trusted anew; the Box's
    unnamed Mesh state moves to it when it's this file's (take_mesh_state)."""
    why = name_problem(name or "")
    if why:
        die(why)
    path = Path(path).expanduser().resolve()
    if SSH_UNSAFE.search(str(path)):
        die(f"{path!r} has a quote or a control character in it - move or rename the file")
    if not path.is_file():
        die(f"no file at {path} - give the path of the Inventory's roster.yml")
    inv = load()
    for x in inv.inventories:
        if same_name(x.name, name):
            die(f"there's already an Inventory named '{x.name}' ({x.path}) - pick another name, or "
                f"`roster inv remove {x.name}` first")
        if same_file(x.path, path):
            die(f"{path} is already the Inventory '{x.name}'")
        if same_file(x.path.parent, path.parent):
            die(f"{path.parent} already holds the Inventory '{x.name}', and ROSTER.md is written next to each "
                "roster.yml: keep each Inventory in its own folder")
    first = inv.active is None
    inv = Inventories(active=name if first else inv.active, inventories=(*inv.inventories, Named(name=name, path=path)))
    save(inv)
    seed_known_hosts(name)
    moved, kept = take_mesh_state(name, path)
    refresh_index(inv)
    refresh_roster_md(inv)
    return Added(first, moved, kept)


def mesh_state_hosts(f: Path) -> set[str] | None:
    """The Host names the Mesh state file F names (members, pending, cuts and their peers); None when it doesn't load."""
    try:
        data = cast("dict[str, Any]", json.loads(f.read_text()))
        hosts = {str(h) for h in cast("list[Any]", data.get("members") or [])}
        hosts |= {str(h) for h in cast("dict[str, Any]", data.get("pending") or {})}
        for host, peers in cast("dict[str, list[Any]]", data.get("cut") or {}).items():
            hosts |= {str(host), *(str(p) for p in peers)}
        return hosts
    except (OSError, ValueError, TypeError, AttributeError):
        return None


def take_mesh_state(name: str, path: Path) -> tuple[Path | None, str | None]:
    """T182 (#346): the Box's one Mesh state (mesh.json, from before Mesh state was per Inventory) moves to the
    Inventory NAME, once, only when everything says it is PATH's (#367's review, F2): roster's unnamed ssh config was
    last written from PATH (the Mesh reaches its Hosts over it), every Host the state names is a Host of PATH, and its
    last complete apply (when it has one) was of PATH's Mesh as it is now. The header alone only says what synced last.
    Otherwise it stays the unnamed Inventory's. A Mesh state NAME has already is never overwritten.
    Returns (where it went, or None; why it stayed, when it's there and didn't move)."""
    shared, mine = mesh_state_file(None), mesh_state_file(name)
    if not shared.is_file():
        return None, None
    if mine.exists():
        return None, f"{name} has a Mesh state already ({mine})"
    source = unnamed_source()
    if source is None or not same_file(source, path):
        return None, ("roster's unnamed ssh config wasn't last written from this file, so nothing says the Mesh state "
                      "is this file's")
    from . import mesh
    from .config import load_config
    try:
        cfg = load_config(path)
    except SystemExit:
        return None, "this file doesn't load, so it can't be compared with the Mesh state"
    hosts = mesh_state_hosts(shared)
    if hosts is None or not hosts <= set(cfg["hosts"]):
        return None, "it names Hosts this file doesn't have"
    try:
        applied = json.loads(shared.read_text()).get("applied")
    except (OSError, ValueError, AttributeError):
        applied = None
    if applied is not None and applied != cast("Any", mesh).digest(cfg):     # mesh.py has no types yet
        return None, "its last apply was of another Mesh than this file's"
    try:
        os.replace(shared, mine)
    except FileNotFoundError:                   # another roster took it first
        return None, None
    return mine, None


def seed_known_hosts(name: str) -> None:
    """NAME's own known_hosts, started as a copy of the one all of this Box's roster.yml files shared before named
    Inventories (~/.ssh/roster_known_hosts), whichever file it was last written from: the trust the Box had, kept."""
    shared, new = known_hosts_file(None), known_hosts_file(name)
    if new.exists() or not shared.is_file():
        return
    shutil.copyfile(shared, new)
    os.chmod(new, 0o600)


def use(name: str) -> None:
    inv = load()
    found = inv.get(name)
    if found is None:
        unknown(name, inv)
    inv = inv.model_copy(update={"active": found.name})
    save(inv)
    refresh_index(inv)
    refresh_roster_md(inv)


class Removed(NamedTuple):
    """What `inv remove` did: whether NAME was the active one, and where its known_hosts and Mesh state went (None
    when it had none)."""

    was_active: bool
    known_hosts: Path | None
    mesh_state: Path | None


def set_aside(f: Path) -> Path | None:
    """Rename F to F.removed-TIME (None when F isn't there)."""
    if not f.exists():
        return None
    kept = f.with_name(f"{f.name}.removed-{time.strftime('%Y%m%d-%H%M%S')}")
    os.replace(f, kept)
    return kept


def remove(name: str) -> Removed:
    """Forget NAME (its roster.yml stays) and its generated ssh config. Its known_hosts and Mesh state are set aside
    (renamed roster_known_hosts-NAME.removed-TIME, mesh-NAME.json.removed-TIME), so a new Inventory of that name never
    inherits another file's keys or Mesh."""
    inv = load()
    x = inv.get(name)
    if x is None:
        unknown(name, inv)
    was_active = same_name(inv.active, x.name)
    inv = Inventories(active=None if was_active else inv.active,
                      inventories=tuple(y for y in inv.inventories if y.name != x.name))
    save(inv)
    ssh_config_file(x.name).unlink(missing_ok=True)
    if generated(legacy_ssh_config_file(x.name)):
        legacy_ssh_config_file(x.name).unlink(missing_ok=True)
    kept = set_aside(known_hosts_file(x.name))
    mesh_kept = set_aside(mesh_state_file(x.name))
    refresh_index(inv)
    refresh_roster_md(inv)
    return Removed(was_active, kept, mesh_kept)


# ---------------------------------------------------------------- ~/.ssh/config: one include for them all

def include_line(path: Path) -> str:
    from .sshops import ssh_quote
    return f"Include {ssh_quote(path)}"


def include_targets(line: str) -> list[str]:
    """The files an `Include` line of ~/.ssh/config names (ssh_path form, ~ and relative paths resolved as ssh does);
    [] for any other line."""
    words = line.strip().replace("=", " ", 1).split(None, 1)
    if len(words) != 2 or words[0].lower() != "include":
        return []
    try:
        args = shlex.split(words[1])
    except ValueError:
        return []
    out: list[str] = []
    for a in args:
        p = Path(os.path.expanduser(a))
        out.append(ssh_path(p if p.is_absolute() else ssh_dir() / p))
    return out


def includes(text: str, path: Path) -> bool:
    """Does the ssh config TEXT include PATH itself (a whole Include line, however written; not a longer name)?"""
    want = ssh_path(path)
    return any(want in include_targets(line) for line in text.splitlines())


def in_use() -> bool:
    """Are named Inventories in use here: listed, or an index left from when they were (refresh_index cleans it)."""
    if ssh_index_file().exists():
        return True
    return list_file().exists() and bool(load().inventories)


class Block(NamedTuple):
    host: str
    text: str


def blocks(path: Path) -> list[Block]:
    """The Host blocks of an ssh config file roster wrote (each with its comment lines), in order."""
    out: list[Block] = []
    for chunk in path.read_text().split("\n\n"):
        hosts = [ln[5:].strip() for ln in chunk.splitlines() if ln.startswith("Host ")]
        if len(hosts) == 1:
            out.append(Block(hosts[0], chunk.strip("\n")))
    return out


def index_order(inv: Inventories) -> list[Path]:
    """The ssh config files the index takes Hosts from, in order: the active Inventory's, the other named ones' (in
    the order they were named), then the one roster writes for a roster.yml that has no name."""
    names = ([inv.active] if inv.active else []) + [x.name for x in inv.inventories if x.name != inv.active]
    return [ssh_config_file(n) for n in names] + [ssh_config_file(None)]


def refresh_index(inv: Inventories | None = None) -> None:
    """Rewrite the index and point ~/.ssh/config at it, once roster has written any ssh config here. With no named
    Inventories left (or inventories.json deleted by hand), ~/.ssh/config includes roster's one file again and the
    index goes. Only sync, setup and `roster inv add/use/remove` call this: they may write ~/.ssh/config."""
    inv = inv if inv is not None else (load() if list_file().exists() else Inventories())
    main = ssh_dir() / "config"
    text = main.read_text() if main.exists() else ""
    index, default = ssh_index_file(), ssh_config_file(None)
    if not inv.inventories:
        if index.exists():
            lines = text.splitlines(keepends=True)
            if any(ssh_path(index) in include_targets(ln) for ln in lines):
                text = "".join(include_line(default) + "\n" if ssh_path(index) in include_targets(ln) else ln
                               for ln in lines)
                replace_file(main, text, 0o600)
            index.unlink(missing_ok=True)
        return
    migrate(inv)
    if not write_index(inv):
        return                                  # nothing synced here yet: the first sync writes it
    if includes(text, index):
        return
    lines = text.splitlines(keepends=True)
    if any(ssh_path(default) in include_targets(ln) for ln in lines):   # roster's one file: the index takes its place
        text = "".join(include_line(index) + "\n" if ssh_path(default) in include_targets(ln) else ln for ln in lines)
    else:                                       # an Include must sit above any Host block, so prepend it
        text = f"{include_line(index)}\n\n{text}"
    main.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    replace_file(main, text, 0o600)


def write_index(inv: Inventories) -> bool:
    """Write the index file alone (nothing else) from the Inventories' ssh config files; False when there's nothing
    to write it from yet."""
    index = ssh_index_file()
    files = [f for f in index_order(inv) if f.is_file()]
    if not (index.exists() or files):
        return False
    seen: set[str] = set()
    out = [INDEX_HEAD]
    for f in files:
        kept: list[str] = []
        left: list[str] = []
        for b in blocks(f):
            if b.host.casefold() in seen:
                left.append(b.host)
            else:
                seen.add(b.host.casefold())
                kept.append(b.text)
        note = f" (left out, as an earlier one has them: {', '.join(left)})" if left else ""
        out.append(f"\n{SECTION}{ssh_path(f)}{note}\n\n" + "".join(t + "\n\n" for t in kept))
    replace_file(index, "".join(out).rstrip("\n") + "\n", 0o600)
    return True


NOTHING = object()


def unnamed_source() -> Path | None:
    """The roster.yml roster's unnamed ssh config (config.d/roster) was last written from, by its header."""
    f = ssh_config_file(None)
    try:
        with f.open(encoding="utf-8", errors="replace") as fh:
            first = fh.readline().rstrip("\n")
    except OSError:
        return None
    head = "# Generated by roster from "
    return Path(first[len(head):]) if first.startswith(head) else None


def refresh_roster_md(inv: Inventories | None = None, skip: Any = NOTHING) -> None:
    """Each Inventory's ROSTER.md (where one was written) again, when what it should say changed: which of its Hosts
    are left out of this Box's ssh config depends on the active Inventory and the others' Hosts. That's every named
    Inventory's and the unnamed one roster's ssh config was last written from. A file whose text stays the same isn't
    touched, so syncing one Inventory leaves the others' alone. SKIP: the Inventory (a name, or None for the unnamed
    one) a sync writes it for already. Each is built for its own Inventory by name: this process's Inventory (which
    serve's other threads read) is never switched. Never fails the command: one that doesn't load is left as it is."""
    from .claude import roster_md, written_by_the_mesh
    from .config import load_config
    inv = inv if inv is not None else load()
    todo: list[tuple[str | None, Path]] = [(x.name, x.path) for x in inv.inventories]
    unnamed = unnamed_source()
    if unnamed is not None and not any(same_file(p, unnamed) for _, p in todo if p.exists()):
        todo.append((None, unnamed))
    for name, path in todo:
        md = path.parent / "ROSTER.md"
        if (skip is not NOTHING and name == skip) or not md.is_file() or written_by_the_mesh(md):
            continue
        try:
            text = roster_md(load_config(path), name)
            if md.read_text() != text:
                md.write_text(text)
        except (SystemExit, OSError):
            continue


def generated(path: Path) -> bool:
    """Did roster write the ssh config file at PATH (its first line is roster's header)? A file by an old name of
    roster's could be the user's own: only roster's are moved or deleted."""
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            return f.readline().startswith("# Generated by roster from ")
    except OSError:
        return False


def foreign_legacy_files(inv: Inventories) -> list[Path]:
    """config.d/roster-NAME files of named Inventories that roster didn't write (left alone, said in check --box)."""
    return [legacy_ssh_config_file(x.name) for x in inv.inventories
            if legacy_ssh_config_file(x.name).is_file() and not generated(legacy_ssh_config_file(x.name))]


def migrate(inv: Inventories) -> None:
    """A named Inventory's ssh config written in config.d by the first version of this (roster-NAME there) moves to
    its own folder, where a user's `Include ~/.ssh/config.d/*` doesn't read it. Only a file roster wrote (its header);
    another roster process may move it first, which is fine."""
    for x in inv.inventories:
        old, new = legacy_ssh_config_file(x.name), ssh_config_file(x.name)
        if not old.is_file() or not generated(old):
            continue
        try:
            if new.exists():
                old.unlink()
            else:
                new.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
                os.replace(old, new)
        except FileNotFoundError:
            pass


def stale() -> bool:
    """Is the index older than a file it copies Hosts from? An older roster (another install on this Box) writing
    roster's unnamed ssh config doesn't know the index: the next roster run rebuilds it."""
    index = ssh_index_file()
    if not index.is_file() or not list_file().exists():
        return False
    inv = load()
    if not inv.inventories:
        return False
    built = index.stat().st_mtime_ns
    return any(f.is_file() and f.stat().st_mtime_ns > built for f in index_order(inv))


INDEX_NOT_WRITTEN = 148         # errors.py's code (row 206)


def rebuild_if_stale() -> None:
    """On any command (reads too): rewrite a stale index file, and nothing else (never ~/.ssh/config). A failure is
    a warning on stderr (code 148), never the command's end: a read-only ~/.ssh must not stop roster or serve."""
    import sys
    try:
        if stale():
            write_index(load())
    except OSError as e:
        print(f"warning: [{INDEX_NOT_WRITTEN}] {ssh_index_file()} is older than this Box's ssh config files and "
              f"couldn't be rewritten ({e.strerror or type(e).__name__}): `ssh NAME` may use Hosts as they were "
              "- run `roster sync` once it can be written", file=sys.stderr, flush=True)


def index_hosts() -> dict[str, set[str]] | None:
    """{ssh config file (ssh_path): the Host names the index took from it}, or None when ~/.ssh/config doesn't include
    the index."""
    main, index = ssh_dir() / "config", ssh_index_file()
    if not (main.is_file() and index.is_file() and includes(main.read_text(), index)):
        return None
    out: dict[str, set[str]] = {}
    current = None
    for line in index.read_text().splitlines():
        if line.startswith(SECTION):
            current = line[len(SECTION):].split(" (left out", 1)[0]
            out[current] = set()
        elif line.startswith("Host ") and current is not None:
            out[current].add(line[5:].strip())
    return out


def unnamed_from_elsewhere() -> Path | None:
    """For a run on a roster.yml that isn't named: the roster.yml roster's one unnamed ssh config (config.d/roster) was
    written from, when it's another file, so `ssh NAME` reaches that file's Hosts, never this one's (#367's review, F1;
    its header names it, or the file itself when it has none). None for a named run, for the file it was written from,
    when there's no such file, or when no roster.yml was looked up."""
    from .common import current_config_path, current_inventory
    here = current_config_path()
    if current_inventory() is not None or here is None or not ssh_config_file(None).is_file():
        return None
    source = unnamed_source()
    if source is not None and same_file(source, here):
        return None
    return source or ssh_config_file(None)


def reachable_hosts(name: Any = CURRENT) -> set[str] | None:
    """The Hosts of the Inventory NAME (default: this run's) a plain `ssh NAME` reaches through roster's ssh config:
    from the index, or from roster's one file when ~/.ssh/config includes it; None when neither is included, and for
    this run when it's on a roster.yml that isn't named while roster's unnamed ssh config is another file's."""
    if name is CURRENT and unnamed_from_elsewhere() is not None:
        return None
    ours = ssh_config_file(name)
    if not ours.is_file():
        return None
    by_file = index_hosts()
    if by_file is not None:
        return by_file.get(ssh_path(ours), set())
    main = ssh_dir() / "config"
    if main.is_file() and includes(main.read_text(), ours):
        return {b.host for b in blocks(ours)}
    return None


def left_out_hosts(name: Any = CURRENT) -> set[str]:
    """The Inventory NAME's Hosts (default: this run's) the index leaves out, because an earlier Inventory has a Host
    by that name."""
    ours = ssh_config_file(name)
    by_file = index_hosts()
    if by_file is None or not ours.is_file():
        return set()
    return {b.host for b in blocks(ours)} - by_file.get(ssh_path(ours), set())


