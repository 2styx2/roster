//! `roster setup --undo`: remove what roster put on the Hosts and the Box,
//! and nothing else. Each Host loses this Box's Mesh, then this Box's key
//! line, last, since that cuts off roster's own way in. The Box's files go
//! only once every Host is done: a rerun needs them to reach the rest.

use crate::inventory::{Host, Inventory};
use crate::setup::{beside_inventory, dry, expand, failed, home, read, save};
use crate::{Fail, claude, mesh, remote, sshconf};
use std::path::Path;

const REMOVE_KEY: &str = include_str!("sh/remove-key.sh");
const OPTS: [&str; 4] = ["-o", "BatchMode=yes", "-o", "ConnectTimeout=10"];

/// `setup` has set the dry-run flag; opening the Inventory scrubbed the secret variables.
pub fn run(inv: &Inventory) -> Result<(), Fail> {
    let mut undone = 0;
    for (i, h) in inv.hosts.iter().enumerate() {
        let skip = |why: &str| eprintln!("roster: {}: skipped: {why}", h.name);
        if !h.reviewed {
            skip("unreviewed");
        } else if !h.enroll {
            skip("a Password Host (enroll: false)");
        } else if h.os == "windows" {
            skip("os: windows; remove the Box key there by hand");
        } else if let Err(why) = host(inv, i) {
            eprintln!("roster: {}: {why}", h.name);
            undone += 1;
        }
    }
    if undone > 0 {
        return Err(failed(format!(
            "{undone} Host{} not done; run `roster setup --undo` again to finish",
            if undone == 1 { "" } else { "s" }
        )));
    }
    box_files(inv)
}

/// Undo Host `i`: its Mesh, then the Box key line. A Host that refuses the
/// Box key has nothing of this Box's that roster can reach, so it's done.
/// When the Mesh step fails, the key line stays, so a rerun can get back in.
fn host(inv: &Inventory, i: usize) -> Result<(), String> {
    let h: &Host = &inv.hosts[i];
    if !mesh::undo(inv, i, dry()).map_err(|why| format!("Mesh: {why}"))? {
        return Ok(());
    }
    let vars = [
        ("BOX", inv.box_name.as_str()),
        ("DRY", if dry() { "1" } else { "" }),
    ];
    let ran = remote::run(&h.name, &OPTS, &remote::script(&vars, REMOVE_KEY), None)
        .map_err(|e| format!("can't run ssh: {e}"))?;
    match (ran.code, ran.stdout.trim()) {
        (0, "removed") => println!("{}: removed the Box key", h.name),
        (0, "present") => println!("{}: would remove the Box key", h.name),
        (0, _) => {}
        (255, _) if ran.why().contains("Permission denied") => {}
        (255, _) => return Err(format!("down: {}", ran.why())),
        (code, _) => {
            return Err(format!(
                "removing the Box key failed ({code}): {}",
                ran.why()
            ));
        }
    }
    Ok(())
}

/// The ssh config and its Include, the known_hosts file, ROSTER.md, the
/// CLAUDE.md import and the deny rules. The Box key stays.
fn box_files(inv: &Inventory) -> Result<(), Fail> {
    let ssh = home().join(".ssh");
    let conf = ssh.join("config.d/roster");
    remove_if(&conf, "# Generated by roster from ")?;
    let line = sshconf::include_line(&conf);
    edit(&ssh.join("config"), |t| sshconf::without_line(t, &line))?;
    remove_if(&ssh.join("roster_known_hosts"), "")?;
    let dir = beside_inventory(inv);
    remove_if(&dir.join("ROSTER.md"), "<!-- generated by roster from ")?;
    edit(&dir.join("CLAUDE.md"), claude::without_import)?;
    let settings = dir.join(".claude/settings.json");
    edit(&settings, |t| {
        claude::without_deny(t).unwrap_or_else(|()| {
            let path = settings.display();
            eprintln!("roster: warning: {path} isn't valid JSON; left it alone");
            None
        })
    })?;
    if !dry() && !settings.exists() {
        let _ = std::fs::remove_dir(dir.join(".claude"));
    }
    let key = expand(&inv.key_path);
    if key.exists() {
        println!(
            "{} the Box key {}; delete it and its .pub by hand once nothing needs it",
            if dry() { "would keep" } else { "kept" },
            key.display()
        );
    }
    Ok(())
}

/// Delete `path` if its text starts with `mark` (roster wrote it); warn
/// and leave it otherwise.
fn remove_if(path: &Path, mark: &str) -> Result<(), Fail> {
    match read(path)? {
        None => Ok(()),
        Some(text) if !text.starts_with(mark) => {
            eprintln!(
                "roster: warning: {} wasn't written by roster; left it alone",
                path.display()
            );
            Ok(())
        }
        Some(_) => remove(path),
    }
}

/// Rewrite `path` with what `change` leaves of it (None: nothing to take
/// out), deleting it when nothing but whitespace is left.
fn edit(path: &Path, change: impl FnOnce(&str) -> Option<String>) -> Result<(), Fail> {
    let Some(old) = read(path)? else {
        return Ok(());
    };
    match change(&old) {
        None => Ok(()),
        Some(new) if new.trim().is_empty() => remove(path),
        Some(new) => save(path, &new, 0o600),
    }
}

fn remove(path: &Path) -> Result<(), Fail> {
    if dry() {
        println!("would remove {}", path.display());
        return Ok(());
    }
    std::fs::remove_file(path).map_err(|e| failed(format!("{}: {e}", path.display())))?;
    println!("removed {}", path.display());
    Ok(())
}
