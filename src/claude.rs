//! What Claude reads: `ROSTER.md`, the `@ROSTER.md` import in `CLAUDE.md`,
//! and the settings that keep Claude out of `~/.ssh`.

use crate::inventory::{Host, Inventory};

/// More Hosts than this and ROSTER.md gives a summary instead of the table.
pub const INLINE_LIMIT: usize = 60;

/// The rules every `.claude/settings.json` beside roster.yml must deny.
pub const DENY: [&str; 2] = ["Read(~/.ssh/**)", "Edit(~/.ssh/**)"];

/// With `claude: true`: the user's own settings allow these without asking.
pub const GRANT: &str = "- You have the user's permission to log in to these Hosts: `ssh`, `scp`, `rsync` and `roster ls`/`check`/`run` are allowed in Claude's settings, on this machine and as root on Mesh Hosts. The rules below still apply.\n";

const GUIDE: &str = "\
# Network access

This machine already has access to the Hosts below. Never ask the user for an address, user name or password for them: roster handles it.

## How to connect
- **access = key**: `ssh <name> '<command>'` (for example `ssh <name> 'uptime'`); `scp` and `rsync` take the same names.
- **access = password** (switches, appliances): `roster run <name> -- <command>`. roster fetches the password itself.
- **access = unreviewed**: found by a scan and not set up yet. Don't try to log in; tell the user it needs reviewing in roster.yml.
- To find a Host by name, group, type or product: `roster ls <word>`. Add `--json` to read the data rather than show it.
- If a Host doesn't respond, `roster check <name> --json` shows which step fails; report what you find.
- Web UIs: open the URL in the browser. If it shows a login page, ask the user to sign in.
- A service marked **(login)** has a stored login: a password, or a token login. To call its web API run `roster web <name> [service] METHOD /path`, with `-d '<body>'` and `-H 'Header: value'` as needed (for example `roster web box-a api POST /api/v1/jobs -d '{\"name\": \"backup\"}'`). roster logs in with the vault credentials and you see only the response. Ask before any request that changes something (POST, PUT, PATCH, DELETE).
- To run a command as root: `roster run --sudo <name> -- <command>` (for example `roster run --sudo box-a -- systemctl restart nginx`). roster gives sudo its password itself.

## Rules
- Never read, print or copy private keys (`~/.ssh/`), and never try to retrieve passwords: don't run `bw` or any other password-manager command yourself.
- Never ask for or handle a password or token: never echo a password into `sudo` or use `sudo -S` yourself, and never call a web API with `curl` and credentials yourself. Use `roster run --sudo` and `roster web`.
- If roster says the vault is locked, tell the user; they unlock it in their own terminal with `roster vault unlock`.
- Ask before changing state on a Host: restarts, installs, deletes, config edits, writes to databases.

## Groups
";

/// ROSTER.md's text. Vault references (`auth`) are never written: a service
/// with a stored login is only marked `(login)`.
pub fn roster_md(inv: &Inventory) -> String {
    let file = inv.path.file_name().unwrap_or_default().to_string_lossy();
    let mut md = format!(
        "<!-- generated by roster from {file} - regenerate with `roster sync` -->\n{GUIDE}"
    );
    if inv.claude {
        md = md.replacen(
            "## How to connect\n",
            &format!("## How to connect\n{GRANT}"),
            1,
        );
    }
    let mut hosts: Vec<&Host> = inv.hosts.iter().collect();
    hosts.sort_by(|a, b| (&a.group, &a.name).cmp(&(&b.group, &b.name)));
    for g in &inv.groups {
        let members: Vec<_> = hosts.iter().filter(|h| h.group == g.name).collect();
        if members.is_empty() {
            continue;
        }
        md += &format!("- **{}**", g.name);
        if !g.title.is_empty() {
            md += &format!(" - {}", g.title);
        }
        let all_key = members.iter().all(|h| h.enroll);
        let access = if all_key { "key" } else { "password/mixed" };
        md += &format!(" ({} hosts, {access} access)", members.len());
        if !g.description.is_empty() {
            md += &format!(": {}", g.description);
        }
        md.push('\n');
    }
    md += "\n## Hosts\n";
    if hosts.len() > INLINE_LIMIT {
        md += &format!(
            "{} hosts - too many to list here. Find one with `roster ls <word>`.\n",
            hosts.len()
        );
        md += &format!("- Products: {}\n", counts(&hosts, |h| &h.product));
        md += &format!("- Types: {}\n", counts(&hosts, |h| &h.r#type));
        return md;
    }
    md +=
        "| name | title | type | product | address | access | web UI | services | description |\n";
    md += "|---|---|---|---|---|---|---|---|---|\n";
    for h in hosts {
        let services: Vec<String> = h
            .services
            .iter()
            .map(|s| {
                let stored = s
                    .auth
                    .as_deref()
                    .is_some_and(|a| !a.is_empty() && a != "prompt");
                let mark = if stored && s.login != "none" {
                    " (login)"
                } else {
                    ""
                };
                format!("{}:{}{mark}", s.name, s.port)
            })
            .collect();
        let row = [
            &*h.name,
            &h.title,
            &h.r#type,
            &h.product,
            &format!("{}@{}:{}", h.user, h.ip, h.port),
            h.access(),
            h.web.as_deref().unwrap_or(""),
            &services.join(", "),
            &h.description,
        ];
        for c in row {
            md += &format!("| {} ", c.replace('|', "\\|").replace('\n', " "));
        }
        md += "|\n";
    }
    md
}

/// `a (2), b (1)`, sorted, with `(none)` for an empty value.
fn counts(hosts: &[&Host], field: impl Fn(&Host) -> &String) -> String {
    let mut c = std::collections::BTreeMap::new();
    for h in hosts {
        let v = field(h);
        *c.entry(if v.is_empty() { "(none)" } else { v })
            .or_insert(0) += 1;
    }
    let parts: Vec<_> = c.iter().map(|(k, n)| format!("{k} ({n})")).collect();
    parts.join(", ")
}

/// CLAUDE.md with the import `line` (`@ROSTER.md`, or `@PATH` in the user's
/// own CLAUDE.md), or None when it's there already.
pub fn with_import(old: &str, line: &str) -> Option<String> {
    if old.lines().any(|l| l.trim() == line) {
        return None;
    }
    let mut text = old.trim_end().to_string();
    if !text.is_empty() {
        text += "\n\n";
    }
    Some(text + line + "\n")
}

/// CLAUDE.md without the import `line` and the blank line `with_import`
/// put before it; None when there's no such line.
pub fn without_import(old: &str, line: &str) -> Option<String> {
    let text = crate::sshconf::without_line(old, line)?;
    let text = text.trim_end();
    Some(match text.is_empty() {
        true => String::new(),
        false => format!("{text}\n"),
    })
}

/// What Claude may run without asking, with `claude: true` (the default):
/// ssh to the Hosts, directly or through roster.
pub const ALLOW: [&str; 6] = [
    "Bash(ssh:*)",
    "Bash(scp:*)",
    "Bash(rsync:*)",
    "Bash(roster ls:*)",
    "Bash(roster check:*)",
    "Bash(roster run:*)",
];

/// Auto mode's classifier reads plain sentences, and suspends shell allow
/// rules when `classifyAllShell` is on: this says the same in words.
pub const AUTO: [&str; 2] = [
    "$defaults",
    "Logging in with ssh, scp, rsync or `roster run` to the Hosts listed in ROSTER.md (roster's Inventory and Mesh), and running commands there, is authorized by the user",
];

/// A rule list in settings.json: section, list, rules.
pub type Rules = (&'static str, &'static str, &'static [&'static str]);

/// The lists roster keeps in a user's own `~/.claude/settings.json`.
pub const USER: [Rules; 3] = [
    ("permissions", "allow", &ALLOW),
    ("permissions", "deny", &DENY),
    ("autoMode", "allow", &AUTO),
];

/// The list beside roster.yml (a project's settings; auto mode ignores it).
pub const LOCAL: [Rules; 1] = [("permissions", "deny", &DENY)];

/// The settings with (`on`) or without each list's rules, every other key
/// kept (keys come out sorted). A list left empty goes, then its section; "" when
/// nothing is left at all. `$defaults` (auto mode's own rules) is added
/// with the rest but never removed, and a list of only `$defaults` counts as
/// empty. None: nothing to change. Err: not a JSON object.
pub fn rules(old: Option<&str>, on: bool, lists: &[Rules]) -> Result<Option<String>, ()> {
    let mut data: serde_json::Value = match old {
        None if !on => return Ok(None),
        None => serde_json::json!({}),
        Some(text) => serde_json::from_str(text).map_err(|_| ())?,
    };
    let top = data.as_object_mut().ok_or(())?;
    let mut changed = old.is_none();
    for &(section, list, want) in lists {
        if !on && !top.contains_key(section) {
            continue;
        }
        let sec = top.entry(section).or_insert_with(|| serde_json::json!({}));
        let sec = sec.as_object_mut().ok_or(())?;
        let arr = sec.entry(list).or_insert_with(|| serde_json::json!([]));
        let arr = arr.as_array_mut().ok_or(())?;
        let before = arr.len();
        match on {
            true => {
                for r in want {
                    if !arr.iter().any(|x| x == r) {
                        arr.push((*r).into());
                    }
                }
            }
            false => arr.retain(|x| x == "$defaults" || !want.iter().any(|r| x == r)),
        }
        changed |= arr.len() != before;
        if arr.iter().all(|x| x == "$defaults") {
            sec.remove(list);
        }
        if sec.is_empty() {
            top.remove(section);
        }
    }
    if !changed {
        return Ok(None);
    }
    if top.is_empty() {
        return Ok(Some(String::new()));
    }
    let text = serde_json::to_string_pretty(&data).map_err(|_| ())?;
    Ok(Some(text + "\n"))
}
