# item 1's last bullet: load_config_text (an edit, a new Inventory or discover's write checked before it's written)
# named the file from the resolved path, so `../TOKEN/roster.yml`, outside the cwd and $HOME once resolved, showed.
def test_a_text_checked_before_its_written_is_named_from_the_path_as_given(tmp_path, monkeypatch):
    from roster.config import load_config_text
    from roster.errors import InventoryError
    (tmp_path / "cwd").mkdir()
    (tmp_path / OP_SESSION).mkdir()
    (tmp_path / OP_SESSION / "roster.yml").write_text(YML)
    monkeypatch.chdir(tmp_path / "cwd")
    with pytest.raises(InventoryError) as e:
        load_config_text("groups: [unclosed\n", f"../{OP_SESSION}/roster.yml")
    said = f"{e.value.message} {e.value.path}"
    assert "the roster.yml at that path (not repeated)" in said and not leaks(said), said


