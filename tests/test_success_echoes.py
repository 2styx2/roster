def test_the_ssh_config_header_doesnt_name_it_and_later_runs_still_know_it_wrote_that_file(capsys, hidden, fakes,
                                                                                         tmp_path):
    run(capsys, ["-c", hidden, "sync", "--no-vault"])
    written = tmp_path / "home" / ".ssh" / "config.d" / "roster"
    text = written.read_text()
    # #529 item 4: "sha256 of its path", so nobody takes the digest for a secret or a checksum of the file
    assert text.startswith("# Generated by roster from the roster.yml at that path (not repeated), sha256 of its "
                           "path "), text
    assert not leaks(text), text
    from roster import named
    from roster.context import use
    use(None, tmp_path / "cwd" / hidden)
    assert named.unnamed_from_elsewhere() is None        # still this roster.yml's: `ssh NAME` reaches its Hosts


def test_a_header_from_before_its_of_its_path_wording_still_names_the_same_file(hidden):
    """#506's header said `sha256 DIGEST`; a Box synced then still knows that file until the next sync rewrites it."""
    from roster import sshconfig
    old = "the roster.yml at that path (not repeated), sha256 " + sshconfig.source_digest(hidden)
    assert sshconfig.hidden_source(old) and sshconfig.same_source(old, hidden)


