# item 3: after a reload serve held the resolved path, so a later load error for `-c ../TOKEN/roster.yml` (resolved
# outside the cwd and $HOME) took typed_token's skip for such paths and named the folder.
def test_serve_names_a_later_load_error_from_the_path_as_given(tmp_path, monkeypatch):
    from roster import serve
    (tmp_path / "cwd").mkdir()
    (tmp_path / OP_SESSION).mkdir()
    yml = tmp_path / OP_SESSION / "roster.yml"
    yml.write_text(YML)
    monkeypatch.chdir(tmp_path / "cwd")
    state = serve.State(f"../{OP_SESSION}/roster.yml")
    assert state.error is None and state.cfg is not None
    yml.write_text("groups: [unclosed\n")
    state.reload()
    p = state.problem()
    said = f"{p.message} {p.fix} {p.data}"
    assert "(not repeated)" in said and not leaks(said), said


