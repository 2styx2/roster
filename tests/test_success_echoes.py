"""#506 (T255, #502's review): a roster.yml that loads fine, in a token-named folder an older roster made, was still
named in full by the commands that succeed. Each one names it through config.shown_path now, and the load says once
on stderr to rename the folder. conftest gives every test its own HOME and cwd; the stand-in CLIs only."""

from pathlib import Path

import pytest

from roster.cli import main

OP_SESSION = "Ex4mple-0nly_n0tAR3al-op_s3ss10nT0k3n-xyzW"       # made up, op session shaped

YML = """\
defaults:
  user: ops

groups:
  lab:
    hosts:
      esx-02: {ip: 10.0.0.5}
"""


def slices(token):
    return [token[i:i + 10] for i in range(0, len(token) - 10, 5)]


def run(capsys, argv):
    try:
        code = main(argv)
    except SystemExit as e:
        code = e.code
    out = capsys.readouterr()
    return str(code), out.out, out.err


def leaks(text):
    return [x for x in slices(OP_SESSION) if x in text]


@pytest.fixture
def hidden(tmp_path, monkeypatch):
    """A valid roster.yml in a token-named folder in the cwd: `-c TOKEN/roster.yml`."""
    cwd = tmp_path / "cwd"
    (cwd / OP_SESSION).mkdir(parents=True)
    (cwd / OP_SESSION / "roster.yml").write_text(YML)
    monkeypatch.chdir(cwd)
    return f"{OP_SESSION}/roster.yml"


def test_check_box_says_it_loads_without_naming_it(capsys, hidden):
    code, out, err = run(capsys, ["-c", hidden, "check", "--box"])
    assert "roster.yml loads: the roster.yml at that path (not repeated)" in out, out
    assert not leaks(out + err), out + err


# item 2: only the error paths said to rename the folder, so a file that loads never told you.
@pytest.mark.parametrize("command", [["hosts"], ["hosts", "--json"], ["check", "--box"]])
def test_a_hidden_roster_yml_that_loads_says_once_on_stderr_to_rename_its_folder(capsys, hidden, command):
    code, out, err = run(capsys, ["-c", hidden, *command])
    assert err.count("rename the folder (or file) whose name looks like a token") == 1, err
    assert "rename the folder" not in out, out            # stdout stays the command's own (--json above all)
    assert not leaks(out + err), out + err


def test_a_roster_yml_that_is_shown_gets_no_rename_note(capsys, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "lab").mkdir()
