fn mode(path: &std::path::Path) -> u32 {
    use std::os::unix::fs::PermissionsExt;
    std::fs::metadata(path).unwrap().permissions().mode() & 0o777
}

/// Every regular file under `dir`, with its bytes and mtime, sorted.
fn snapshot(dir: &std::path::Path) -> Vec<(std::path::PathBuf, Vec<u8>, std::time::SystemTime)> {
    let mut files = Vec::new();
    let mut todo = vec![dir.to_path_buf()];
    while let Some(d) = todo.pop() {
        for e in std::fs::read_dir(d).unwrap() {
            let e = e.unwrap();
            let m = e.metadata().unwrap();
            if m.is_dir() {
                todo.push(e.path());
            } else if m.is_file() && e.path().extension().is_none_or(|x| x != "log") {
                // The fakes' logs grow with each run (the Host probe); skip them.
                let bytes = std::fs::read(e.path()).unwrap();
                files.push((e.path(), bytes, m.modified().unwrap()));
            }
        }
    }
    files.sort();
    files
}

#[test]
fn setup_writes_roster_md_next_to_roster_yml() {
    let s = Sandbox::new("claude-roster-md");
    s.write("net/roster.yml", INVENTORY);
    let out = s.roster(&["-c", "net/roster.yml", "setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let md = s.home.join("net/ROSTER.md");
    assert_eq!(std::fs::read_to_string(&md).unwrap(), ROSTER_MD);
    assert_eq!(mode(&md), 0o644);
    assert!(
        !s.home.join("ROSTER.md").exists(),
        "not in the working directory"
    );
    assert!(out.stdout.contains(&format!("wrote {}\n", md.display())));
}

#[test]
fn claude_md_imports_roster_md_once_and_keeps_what_was_there() {
    let s = Sandbox::new("claude-md");
    s.write("net/roster.yml", INVENTORY);
    s.write("net/CLAUDE.md", "# Our notes\n\nBe nice.\n");
    let out = s.roster(&["-c", "net/roster.yml", "setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let text = std::fs::read_to_string(s.home.join("net/CLAUDE.md")).unwrap();
    assert_eq!(text, "# Our notes\n\nBe nice.\n\n@ROSTER.md\n");
    s.roster(&["-c", "net/roster.yml", "setup"]);
    let again = std::fs::read_to_string(s.home.join("net/CLAUDE.md")).unwrap();
    assert_eq!(again, text);
}

