#[test]
fn settings_deny_ssh_merged_into_what_was_there() {
    let s = Sandbox::new("claude-settings-merge");
    s.write("net/roster.yml", INVENTORY);
    s.write(
        "net/.claude/settings.json",
        r#"{"model": "x", "permissions": {"allow": ["Bash(ls)"], "deny": ["Read(~/.ssh/**)"]}, "env": {"A": "1"}}"#,
    );
    let out = s.roster(&["-c", "net/roster.yml", "setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let text = std::fs::read_to_string(s.home.join("net/.claude/settings.json")).unwrap();
    let got: serde_json::Value = serde_json::from_str(&text).unwrap();
    let want = serde_json::json!({
        "model": "x",
        "env": {"A": "1"},
        "permissions": {
            "allow": ["Bash(ls)"],
            "deny": ["Read(~/.ssh/**)", "Edit(~/.ssh/**)"],
        },
    });
    assert_eq!(got, want);
    assert!(text.ends_with("}\n"), "{text}");
    // The user's own ~/.claude gets the rules that let Claude log in.
    let own = std::fs::read_to_string(s.home.join(".claude/settings.json")).unwrap();
    assert!(own.contains("Bash(ssh:*)"), "{own}");
}

