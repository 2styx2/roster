#[test]
fn no_secret_reference_reaches_a_written_file_and_a_rerun_changes_nothing() {
    let s = Sandbox::new("claude-rerun");
    s.write("net/roster.yml", INVENTORY);
    let out = s.roster(&["-c", "net/roster.yml", "setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let before = snapshot(&s.home);
    for (path, bytes, _) in &before {
        if path.ends_with("roster.yml") {
            continue;
        }
        let text = String::from_utf8_lossy(bytes);
        for secret in ["api-token-item", "switch-admin-item"] {
            assert!(!text.contains(secret), "{} holds {secret}", path.display());
        }
    }
    let out = s.roster(&["-c", "net/roster.yml", "setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert_eq!(out.stdout, "", "a rerun has nothing to say");
    assert_eq!(snapshot(&s.home), before, "a rerun touches no file");
}

#[test]
fn more_hosts_than_the_inline_limit_get_a_summary() {
    let s = Sandbox::new("claude-summary");
    let mut yml = String::from("defaults: {user: admin}\ngroups:\n  lab:\n    hosts:\n");
    for i in 0..61 {
        let product = if i < 40 { "Widget" } else { "Gadget" };
        let kind = if i % 2 == 0 { "type: vm, " } else { "" };
        yml += &format!("      h-{i:02}: {{ip: 10.0.1.{i}, {kind}product: {product}}}\n");
    }
    s.write("roster.yml", &yml);
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let md = std::fs::read_to_string(s.home.join("ROSTER.md")).unwrap();
    let tail = md.split("## Groups\n").nth(1).unwrap();
    assert_eq!(
        tail,
        "\
- **lab** (61 hosts, key access)

## Hosts
61 hosts - too many to list here. Find one with `roster ls <word>`.
- Products: Gadget (21), Widget (40)
- Types: (none) (30), vm (31)
"
    );
}

#[test]
fn sixty_hosts_are_still_listed() {
    let s = Sandbox::new("claude-sixty");
    let mut yml = String::from("defaults: {user: admin}\ngroups:\n  lab:\n    hosts:\n");
    for i in 0..60 {
        yml += &format!("      h-{i:02}: 10.0.1.{i}\n");
    }
    s.write("roster.yml", &yml);
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let md = std::fs::read_to_string(s.home.join("ROSTER.md")).unwrap();
    assert!(
        md.contains("| h-59 |  |  |  | admin@10.0.1.59:22 | key |"),
        "{md}"
    );
}
