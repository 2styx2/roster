//! `roster setup`, the Box side: the Box key, the ssh config and its Include.
mod common;
use common::Sandbox;

const INVENTORY: &str = r#"
box_name: box-a
defaults: {user: admin}
groups:
  dev:
    hosts:
      box-b:
        ip: 10.0.0.6
        title: Box B
  gear:
    hosts:
      sw-01: {ip: 10.0.0.9, enroll: false, port: 2222}
      win-01: {ip: 10.0.0.7, os: windows, user: Administrator}
      v6-01: "fe80::1%eth0"
"#;

fn read(s: &Sandbox, rel: &str) -> String {
    std::fs::read_to_string(s.home.join(rel)).unwrap_or_default()
}

#[test]
fn setup_makes_the_box_key_once() {
    let s = Sandbox::new("setup-key");
    s.write("roster.yml", INVENTORY);
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let key = s.home.join(".ssh/roster_ed25519");
    assert_eq!(
        read(&s, "ssh-keygen.log"),
        format!(
            "-q -t ed25519 -N  -C roster-managed:box-a -f {}\n",
            key.display()
        )
    );
    assert!(read(&s, ".ssh/roster_ed25519.pub").ends_with("roster-managed:box-a\n"));

    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert_eq!(read(&s, "ssh-keygen.log").lines().count(), 1);
}

#[test]
fn setup_passes_the_bits_for_ecdsa_and_rsa_and_honours_key_path() {
    let s = Sandbox::new("setup-key-bits");
    s.write(
        "roster.yml",
        &format!("key_type: rsa\nkey_path: ~/keys/mine\n{INVENTORY}"),
    );
    std::fs::create_dir_all(s.home.join("keys")).unwrap();
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let log = read(&s, "ssh-keygen.log");
    assert!(
        log.starts_with("-q -t rsa -b 3072 -N  -C roster-managed:box-a -f "),
        "{log}"
    );
    assert!(log.trim_end().ends_with("/keys/mine"), "{log}");
}

#[test]
fn setup_writes_one_ssh_config_block_per_host() {
    let s = Sandbox::new("setup-config");
    s.write("roster.yml", INVENTORY);
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let from = std::fs::canonicalize(s.home.join("roster.yml")).unwrap();
    let common = "    UserKnownHostsFile \"~/.ssh/roster_known_hosts\"
    StrictHostKeyChecking accept-new
    ConnectTimeout 10
    ServerAliveInterval 30
";
    let multiplexed = "    ControlMaster auto
    ControlPath \"~/.ssh/cm-%C\"
    ControlPersist 10m
";
    let key = "    IdentityFile \"~/.ssh/roster_ed25519\"
    IdentitiesOnly yes
";
    let expected = format!(
        "# Generated by roster from {}
# Written whole by `roster setup`: edit roster.yml, not this file.

# Box B [dev]
Host box-b
    HostName 10.0.0.6
    User admin
    Port 22
{common}{multiplexed}{key}
# sw-01 [gear]
Host sw-01
    HostName 10.0.0.9
    User admin
    Port 2222
{common}{multiplexed}    IdentitiesOnly yes
    PubkeyAuthentication no

# v6-01 [gear]
Host v6-01
    HostName fe80::1%%eth0
    User admin
    Port 22
{common}{multiplexed}{key}
# win-01 [gear]
Host win-01
    HostName 10.0.0.7
    User Administrator
    Port 22
{common}    ControlMaster no
{key}",
        from.display()
    );
    assert_eq!(read(&s, ".ssh/config.d/roster"), expected);
    let mode = |rel: &str| {
        use std::os::unix::fs::PermissionsExt;
        std::fs::metadata(s.home.join(rel))
            .unwrap()
            .permissions()
            .mode()
            & 0o777
    };
    assert_eq!(mode(".ssh/config.d/roster"), 0o600);
    assert_eq!(mode(".ssh"), 0o700);
    assert_eq!(mode(".ssh/config.d"), 0o700);
}

#[test]
fn setup_includes_the_config_once_on_top_and_a_rerun_changes_nothing() {
    use std::os::unix::fs::PermissionsExt;
    let s = Sandbox::new("setup-include");
    s.write("roster.yml", INVENTORY);
    let mine = "Host *\n    ServerAliveInterval 60\n";
    let config = s.write(".ssh/config", mine);
    std::fs::set_permissions(&config, std::fs::Permissions::from_mode(0o640)).unwrap();
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    let include = format!(
        "Include \"{}\"\n",
        s.home.join(".ssh/config.d/roster").display()
    );
    assert_eq!(read(&s, ".ssh/config"), format!("{include}{mine}"));
    let mode = std::fs::metadata(&config).unwrap().permissions().mode() & 0o777;
    assert_eq!(mode, 0o640, "an existing file keeps its mode");

    let snapshot = |s: &Sandbox| {
        let mut files = Vec::new();
        for dir in [".ssh", ".ssh/config.d"] {
            for e in std::fs::read_dir(s.home.join(dir)).unwrap() {
                let e = e.unwrap();
                let m = e.metadata().unwrap();
                if m.is_file() {
                    let bytes = std::fs::read(e.path()).unwrap();
                    files.push((e.file_name(), bytes, m.modified().unwrap()));
                }
            }
        }
        files.sort();
        files
    };
    let before = snapshot(&s);
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert_eq!(out.stdout, "", "a rerun has nothing to say");
    assert_eq!(snapshot(&s), before, "a rerun touches no file");
}

#[test]
fn setup_leaves_no_temp_files_and_honours_an_include_already_there() {
    let s = Sandbox::new("setup-no-temp");
    s.write("roster.yml", INVENTORY);
    let mine = "Host *\n    User me\n\ninclude ~/.ssh/config.d/roster\n";
    s.write(".ssh/config", mine);
    let out = s.roster(&["setup"]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert_eq!(read(&s, ".ssh/config"), mine);
    let mut names: Vec<_> = [".ssh", ".ssh/config.d"]
        .iter()
        .flat_map(|d| std::fs::read_dir(s.home.join(d)).unwrap())
        .map(|e| e.unwrap().file_name().into_string().unwrap())
        .collect();
    names.sort();
    assert_eq!(
        names,
        [
            "config",
            "config.d",
            "roster",
            "roster_ed25519",
            "roster_ed25519.pub"
        ]
    );
}

