@posix_shell
def test_uninstall_keeps_roster_when_the_revoke_failed(box):
    home, env = box
    (Path(env["PATH"].split(":")[0]) / "roster").write_text(
        '#!/bin/sh\necho "roster $*" >> "$HOME/calls"\n[ "$1" = revoke ] && exit 1\nexit 0\n')
