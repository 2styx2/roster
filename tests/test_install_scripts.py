FAKES = {
    "roster": '#!/bin/sh\necho "roster $*" >> "$HOME/calls"\n[ "$1" = --version ] && echo "roster 0.4.0"\nexit 0\n',
    "uv": '#!/bin/sh\necho "uv $*" >> "$HOME/calls"\n[ "$1 $2" = "tool list" ] && echo "roster v0.4.0"\nexit 0\n',
    "crontab": '#!/bin/sh\nif [ "$1" = -l ]; then cat "$HOME/crontab" 2>/dev/null; exit 0; fi\n'
               # all of stdin first, as crontab does: it's a pipe from `crontab -l`, reading this same file
               'new=$(cat); printf "%s\\n" "$new" | sed "/^$/d" > "$HOME/crontab"\necho "crontab -" >> "$HOME/calls"\n',
}
CRON_JOB = "*/15 * * * * /home/u/infra/bin/roster-pull >> $HOME/.cache/roster-pull.log 2>&1"
OTHER_JOB = "0 3 * * * /usr/local/bin/backup"


