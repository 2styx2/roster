def run(script, env, *args, answers=None):
    flags = [*([] if answers is not None else ["--yes"]), *args]
    r = subprocess.run(["bash", str(script), *flags], env=env, capture_output=True, text=True, input=answers or "",
                       timeout=120, start_new_session=True)                      # no controlling terminal
    return r


def calls(home):
    f = home / "calls"
    return f.read_text() if f.exists() else ""


@posix_shell
def test_uninstall_dry_run_changes_nothing(box):
    home, env = box
    before = sorted(p.relative_to(home) for p in home.rglob("*"))
    texts = {p: p.read_text() for p in home.rglob("*") if p.is_file()}
    r = run(UNINSTALL_SH, env, "--dry-run")
    assert r.returncode == 0, r.stdout + r.stderr
    assert "would run: roster revoke --all -y" in r.stdout
    assert sorted(p.relative_to(home) for p in home.rglob("*") if p.name != "calls") == before
    assert all(p.read_text() == t for p, t in texts.items())
    assert "uv tool uninstall" not in calls(home)


