    assert "ROSTER_CONFIG" not in bashrc and 'alias ll="ls -l"' in bashrc
    assert "# roster: uv tools" in bashrc                     # shared with uv: kept unless --purge
    assert (home / "infra/roster.yml").exists()               # the team's map stays
    assert not (home / "infra/ROSTER.md").exists() and not (home / "infra/CLAUDE.md").exists()


