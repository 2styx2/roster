def run(script, env, *args, answers=None):
    flags = [*([] if answers is not None else ["--yes"]), *args]
    r = subprocess.run(["bash", str(script), *flags], env=env, capture_output=True, text=True, input=answers or "",
                       timeout=120, start_new_session=True)                      # no controlling terminal
    return r


def calls(home):
    f = home / "calls"
    return f.read_text() if f.exists() else ""


