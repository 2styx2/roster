"""install.sh's companions, update.sh and uninstall.sh, run against a made-up HOME.

roster, uv and crontab are stand-ins here (a real `uv tool uninstall roster` or crontab would change the box running
the tests): each logs how it was called to HOME/calls. The full run on a fresh box (apt, uv, bw, a real sshd Host) is
scripts/test-install.sh, in a container."""

import os
